/**
 * Recreates android/local.properties after `expo prebuild --clean`.
 * Windows default SDK path; override with ANDROID_HOME.
 */
const fs = require('fs');
const path = require('path');

const sdkRoot =
  process.env.ANDROID_HOME ||
  process.env.ANDROID_SDK_ROOT ||
  path.join(process.env.LOCALAPPDATA || '', 'Android', 'Sdk');

const androidDir = path.join(__dirname, '..', 'android');
const target = path.join(androidDir, 'local.properties');

if (!fs.existsSync(androidDir)) {
  console.warn('ensure-local-properties: android/ not found — run expo prebuild first');
  process.exit(0);
}

const escaped = sdkRoot.replace(/\\/g, '\\\\');
const content = `## Auto-generated by scripts/ensure-local-properties.js — do not commit
sdk.dir=${escaped}
`;

fs.writeFileSync(target, content, 'utf8');
console.log(`Wrote ${target}`);
console.log(`sdk.dir=${sdkRoot}`);
